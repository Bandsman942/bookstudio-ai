const catalogs:{[K in Locale]:Record<MessageKey,string>}={fr,en};
export function translate(locale:Locale,key:MessageKey,args?:Record<string,string|number>):string{
  const value=catalogs[locale][key]??catalogs.fr[key];
  return value.replace(/\{(\w+)\}/g,(_,name:string)=>String(args?.[name]??''));
}
